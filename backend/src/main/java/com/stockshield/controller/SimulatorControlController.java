package com.stockshield.controller;

import com.stockshield.model.SensorStatus;
import com.stockshield.repository.AlertLogRepository;
import com.stockshield.repository.SensorRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.Map;

@RestController
@RequestMapping("/api/simulator")
@RequiredArgsConstructor
@Slf4j
public class SimulatorControlController {

    private final SensorRepository sensorRepository;
    private final AlertLogRepository alertLogRepository;

    @PostMapping("/reset")
    public ResponseEntity<Map<String, Object>> resetToHardwareMode() {
        log.info("Resetting sensors to OFFLINE and clearing simulated alerts for physical hardware mode");
        
        // Reset all sensors to OFFLINE
        var sensors = sensorRepository.findAll();
        for (var s : sensors) {
            s.setStatus(SensorStatus.OFFLINE);
            s.setLastReading(null);
            s.setLastSeen(null);
        }
        sensorRepository.saveAll(sensors);

        // Clear alerts generated by simulator
        alertLogRepository.deleteAll();

        return ResponseEntity.ok(Map.of(
                "status", "success",
                "message", "Reset completed: All sensors OFFLINE, alerts cleared. Ready for hardware."
        ));
    }
}
